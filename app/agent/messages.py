"""Тексты для механика, которые пишет код, а не модель (словарь — на будущее для языков).

Предупреждения режима (правила 4–6) код ставит первой строкой ответа сам: так «первая фраза»
не зависит от того, послушалась ли модель промпта.
"""
from app.policy import modes

WARNINGS_RU = {
    modes.W_CHECK_FAILED: ("Запись непригодна для диагностики — выводов о двигателе нет. "
                           "Повторите запись."),
    modes.W_ML_INCONSISTENT: ("Результат ML противоречит устройству этого двигателя — такой неисправности "
                              "у него быть не может. Повторите запись или проверьте вручную; заявка не создаётся."),
    modes.W_SIGNAL_WARNING: "При записи были помехи — результат нужно подтвердить ручной проверкой.",
    modes.W_LOW_CONFIDENCE: "Низкая уверенность ML-модели — результат нужно подтвердить ручной проверкой.",
    modes.W_INJECTION: "В описании от ML-сервиса обнаружен посторонний текст, проигнорирован.",
}

# Порядок, в котором предупреждения идут в первой строке: сначала то, что отменяет выводы.
WARNING_ORDER = (modes.W_CHECK_FAILED, modes.W_ML_INCONSISTENT, modes.W_SIGNAL_WARNING,
                 modes.W_LOW_CONFIDENCE, modes.W_INJECTION)

TOOL_STEPS_RU = {
    modes.GET_DIAGNOSIS: "получил результат диагностики",
    modes.SEARCH_MANUAL: "искал в руководстве",
    modes.DRAFT_TICKET: "подготовил черновик заявки",
    modes.GET_TREND: "оценил тенденцию по прошлым проверкам",
    modes.GET_HISTORY: "посмотрел историю машины",
}

LLM_UNAVAILABLE = "Модель сейчас недоступна — повторите запрос через минуту. Результат диагностики не потерян."
PROMPT_LEAK = "Это служебная информация, её я не показываю. Задайте вопрос о машине или результате проверки."


def warning_line(warnings) -> str:
    """Одна строка предупреждений для начала ответа (пустая, если предупреждений нет)."""
    present = [w for w in WARNING_ORDER if w in set(warnings)]
    return " ".join(f"⚠ {WARNINGS_RU[w]}" for w in present)
